#!/usr/bin/env node
/**
 * Builds supabase/cloud-sync.sql: every file in supabase/migrations, in order, as ONE
 * idempotent script you can paste into the Supabase Cloud SQL Editor.
 *
 *   npm run db:cloud-sql
 *
 * Why: Docker (`supabase db reset`) applies supabase/migrations automatically; a Supabase Cloud
 * project does not. Running this file brings a Cloud database up to the same schema as Docker,
 * so every branch/commit of the app finds the tables it needs. Safe to run again at any time.
 * It never includes supabase/seed.sql (that file creates test users with a known password).
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase");
const dir = join(root, "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const versions = new Map();
for (const f of files) {
  const v = f.split("_")[0];
  if (versions.has(v)) {
    console.error(`Duplicate migration version ${v}: ${versions.get(v)} and ${f}. Renumber one of them.`);
    process.exit(1);
  }
  versions.set(v, f);
}

const parts = [
  `-- ============================================================================\n` +
    `-- FIDES - Supabase Cloud sync (generated by scripts/build-cloud-sql.mjs - do not edit)\n` +
    `-- Paste the WHOLE file into Supabase Dashboard -> SQL Editor -> Run.\n` +
    `-- Idempotent: safe on an empty project, a half-migrated project, or re-running.\n` +
    `-- Contains ${files.length} migrations: ${files[0]} ... ${files[files.length - 1]}\n` +
    `-- ============================================================================\n`,
];
for (const f of files) {
  const sql = readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trimEnd();
  parts.push(`\n-- >>>>>>>>>> ${f} >>>>>>>>>>\n${sql}\n`);
}
writeFileSync(join(root, "cloud-sync.sql"), parts.join(""));
console.log(`Wrote supabase/cloud-sync.sql (${files.length} migrations).`);
